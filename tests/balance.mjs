// Builds js/data/balance.js: bot-vs-bot win rates for every pair of official decks.
import fs from 'node:fs';
import { Game } from '../js/engine/game.js';
import { botAnswer } from '../js/engine/bot.js';
import { DECKS } from '../js/data/decks.js';
const N = Number(process.argv[2] || 60);
const keys = Object.keys(DECKS);
function mul(seed) { let a = seed >>> 0; return () => { a |= 0; a = (a + 0x6D2B79F5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const res = {}; let seed = 900000, total = 0; const rounds = [];
for (const A of keys) for (const B of keys) {
  const r = { games: 0, aWins: 0, bWins: 0, draws: 0 };
  for (let k = 0; k < N; k++) {
    const rand = mul(++seed);
    const g = new Game({ seed, players: [{ name: A, leader: DECKS[A].leader, deck: DECKS[A].main }, { name: B, leader: DECKS[B].leader, deck: DECKS[B].main }], options: {} });
    let steps = 0;
    while (g.pending && !g.s.over && steps++ < 40000 && g.s.round <= 80) { const q = g.pending; g.respond(q.player, botAnswer(g, q, rand, { fuzz: 0 })); }
    if (!g.s.over) continue;
    r.games++; total++; rounds.push(g.s.round);
    if (g.s.winner === 'draw') r.draws++; else if (g.s.winner === 0) r.aWins++; else r.bWins++;
  }
  res[A + '|' + B] = r;
}
const avgRounds = rounds.reduce((a, b) => a + b, 0) / rounds.length;
fs.writeFileSync(new URL('../js/data/balance.js', import.meta.url), '// Generated by tests/balance.mjs — bot-vs-bot results.\nexport const BALANCE = ' + JSON.stringify({ perPair: N, total, avgRounds: +avgRounds.toFixed(1), date: new Date().toISOString().slice(0, 10), res }) + ';\n');
console.log('games', total, 'avg rounds', avgRounds.toFixed(1));
