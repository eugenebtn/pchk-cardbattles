/** Wrap known terms in card text with hover tooltips. Input must already be HTML-escaped. */
export function linkTerms(html) {
  const hits = [];
  GLOSSARY.forEach(([re, title, text], k) => {
    const r = new RegExp(re.source, 'g');
    let m;
    while ((m = r.exec(html))) { hits.push({ a: m.index, b: m.index + m[0].length, k, title, text }); if (!m[0].length) r.lastIndex++; }
  });
  hits.sort((x, y) => x.a - y.a || (y.b - y.a) - (x.b - x.a) || x.k - y.k);
  let out = '', pos = 0;
  for (const h of hits) {
    if (h.a < pos) continue;
    out += html.slice(pos, h.a) + `<span class="term" data-tip="${h.title}|${h.text}">${html.slice(h.a, h.b)}</span>`;
    pos = h.b;
  }
  return out + html.slice(pos);
}

/** Global delayed tooltips for any element with data-tip="Title|Text" (or plain text). */
export function installTooltips() {
  const tip = document.createElement('div');
  tip.className = 'tooltip hidden';
  document.body.appendChild(tip);
  let timer = null, cur = null;
  const show = (el, x, y) => {
    const raw = el.getAttribute('data-tip') || '';
    const [t, body] = raw.includes('|') ? raw.split('|') : ['', raw];
    tip.innerHTML = (t ? `<b>${t}</b>` : '') + (body ? `<div>${body}</div>` : '');
    tip.classList.remove('hidden');
    const w = tip.offsetWidth, h = tip.offsetHeight;
    let px = x + 14, py = y + 18;
    if (px + w > window.innerWidth - 8) px = x - w - 14;
    if (py + h > window.innerHeight - 8) py = y - h - 14;
    tip.style.left = Math.max(8, px) + 'px'; tip.style.top = Math.max(8, py) + 'px';
  };
  const hide = () => { clearTimeout(timer); timer = null; cur = null; tip.classList.add('hidden'); };
  document.addEventListener('mouseover', (e) => {
    const el = e.target.closest && e.target.closest('[data-tip]');
    if (el === cur) return;
    hide();
    if (!el) return;
    cur = el;
    const { clientX: x, clientY: y } = e;
    timer = setTimeout(() => show(el, x, y), 450);
  });
  document.addEventListener('mousemove', (e) => { if (!tip.classList.contains('hidden') && cur) { /* keep position stable */ } });
  document.addEventListener('mousedown', hide, true);
  document.addEventListener('scroll', hide, true);
  // Touch: tapping a term shows its tip.
  document.addEventListener('click', (e) => {
    const el = e.target.closest && e.target.closest('.term,[data-tip-tap]');
    if (!el || !window.matchMedia('(hover: none)').matches) return;
    e.stopPropagation();
    const r = el.getBoundingClientRect();
    show(el, r.left, r.bottom);
    setTimeout(hide, 4000);
  }, true);
}
